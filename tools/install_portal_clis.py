#!/usr/bin/env python3
"""Install the dependencies of every portal CLI under .agents/skills/.

Run from anywhere: python3 tools/install_portal_clis.py [--dry-run]

The CLIs are discovered, not listed: every `.agents/skills/*/cli/package.json`
is installed, the same glob CI's discover-clis job uses. A portal generated by
/add-portal or copied from another fork is therefore picked up on a fresh clone
without anyone editing an install loop, and a portal removed from the tree
stops being asked for.

One command for every shell, since Python is already a prerequisite - the
README previously carried a PowerShell and a Bash loop, each with its own
hand-copied list of portal names.

A manifest that declares an npm/bun lifecycle script or trustedDependencies is
skipped and reported instead of installed: those are the hooks that run code
during `bun install`, and tools/security_guards.py forbids them in-tree. A
borrowed portal that carries one gets read by a human before it runs.

Each CLI installs independently; one failure does not stop the rest. Exit 0
when every CLI installed, 1 when bun is missing, a manifest was skipped, or an
install failed.
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))

from security_guards import FORBIDDEN_SCRIPTS  # noqa: E402


# Real-path-only candidates: locations bun is documented to land in, plus
# package-manager installs. We do not consult $PATH here - shutil.which already
# did. Each entry is checked for executability; the first hit wins. No platform
# branching beyond what is already on disk: a candidate that does not exist is
# simply skipped, so this list is safe to scan on Windows even though most
# entries are Unix-shaped.
_BUN_FALLBACK_CANDIDATES = (
    "~/.bun/bin/bun",                              # https://bun.sh/install
    "/home/linuxbrew/.linuxbrew/bin/bun",          # Linuxbrew, system-wide
    "/opt/homebrew/bin/bun",                       # Homebrew on Apple Silicon
    "/usr/local/bin/bun",                          # Homebrew on Intel macOS, manual Linux installs
    "/usr/bin/bun",                                # apt/equivalent distro packages
    "~/.local/bin/bun",                            # pip-style user installs (bun-bin)
)


def _expand_candidate(raw: str) -> list[Path]:
    """Return [path] if a documented bun install location is executable, else [].

    `~` expands to $HOME; the rest is treated as a literal path. Returning a
    list (rather than a Path) keeps `resolve_bun` a flat loop and leaves room
    for glob expansion if a future candidate needs it.
    """
    expanded = Path(os.path.expanduser(raw))
    if expanded.is_file() and os.access(expanded, os.X_OK):
        return [expanded]
    return []


def resolve_bun() -> str | None:
    """Absolute path to the bun binary, or None if no candidate exists.

    Checks $PATH first via shutil.which, then the documented install locations.
    The fallback exists because the official installer only writes to
    ~/.bashrc/~/.zshrc: in non-interactive shells (CI, subprocesses, Debian
    logins that source ~/.profile) ~/.bun/bin is on disk but not on $PATH, and
    the script used to abort even though bun was installed. See #707.
    """
    which = shutil.which("bun")
    if which:
        return which
    for candidate in _BUN_FALLBACK_CANDIDATES:
        for path in _expand_candidate(candidate):
            return str(path)
    return None


def _bun_install_hint() -> str:
    """Actionable next-step message when no bun binary can be found."""
    return (
        "No bun binary was found. Install one and re-run:\n"
        "  - bun.sh installer: curl -fsSL https://bun.sh/install | bash "
        "(installs to ~/.bun/bin, then `export PATH=\"$HOME/.bun/bin:$PATH\"` "
        "in your shell's login rc and open a new shell)\n"
        "  - Homebrew: brew install bun\n"
        "  - Linuxbrew: brew install bun (add brew to PATH the same way)\n"
        "  - apt (if your distro ships it): see your package manager\n"
        "Bun's docs: https://bun.sh"
    )


def discover(root: Path = ROOT) -> list[Path]:
    """Return each portal CLI directory, sorted by portal name."""
    return sorted(p.parent for p in (root / ".agents" / "skills").glob("*/cli/package.json"))


def unsafe_reason(cli_dir: Path) -> str | None:
    """Why this manifest must not be installed unattended, or None when it is safe."""
    try:
        data = json.loads((cli_dir / "package.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return f"unreadable package.json ({exc})"
    if not isinstance(data, dict):
        return "package.json is not a JSON object"
    scripts = data.get("scripts", {})
    bad = sorted(FORBIDDEN_SCRIPTS & set(scripts)) if isinstance(scripts, dict) else []
    if bad:
        return f"declares lifecycle script(s) {bad}"
    if "trustedDependencies" in data:
        return "declares trustedDependencies"
    return None


def install(cli_dirs: list[Path], bun: str, dry_run: bool, root: Path = ROOT, run=subprocess.run) -> int:
    failures = []
    for cli_dir in cli_dirs:
        name = cli_dir.parent.name
        reason = unsafe_reason(cli_dir)
        if reason:
            print(f"SKIP  {name}: {reason} - read its code, then run `bun install` in "
                  f"{cli_dir.relative_to(root).as_posix()} yourself if you trust it")
            failures.append(name)
            continue
        if dry_run:
            print(f"would install  {name}")
            continue
        print(f"installing  {name}", flush=True)
        if run([bun, "install"], cwd=cli_dir).returncode != 0:
            print(f"FAIL  {name}: bun install exited non-zero")
            failures.append(name)
    if failures:
        print(f"\n{len(failures)} of {len(cli_dirs)} portal CLI(s) not installed: {', '.join(failures)}")
        return 1
    verb = "would be installed" if dry_run else "installed"
    print(f"\nAll {len(cli_dirs)} portal CLI(s) {verb}.")
    return 0


def _force_utf8_output() -> None:
    """Write UTF-8 whatever the host's default encoding is (a fork's portal name may not be ASCII)."""
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)  # absent on a StringIO under test
        if reconfigure:
            reconfigure(encoding="utf-8")


def main() -> int:
    _force_utf8_output()
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dry-run", action="store_true", help="list what would be installed, run nothing")
    args = ap.parse_args()

    cli_dirs = discover()
    if not cli_dirs:
        print("No portal CLIs found under .agents/skills/*/cli/ - nothing to install.")
        return 0
    bun = resolve_bun()
    if not bun and not args.dry_run:
        print(_bun_install_hint())
        return 1
    if bun and Path(bun).parent.as_posix() not in os.environ.get("PATH", "").split(os.pathsep):
        # bun found off $PATH (e.g. ~/.bun/bin in a non-interactive shell).
        # Prepend its directory to PATH so subprocesses it spawns (and any
        # postinstall the manifest runs, though we forbid those) behave the
        # same as in an interactive shell where ~/.bashrc was sourced.
        os.environ["PATH"] = f"{Path(bun).parent}{os.pathsep}{os.environ.get('PATH', '')}"
    return install(cli_dirs, bun or "bun", args.dry_run)


if __name__ == "__main__":
    sys.exit(main())
